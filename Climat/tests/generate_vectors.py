"""Independent reference frames, using Python's CRC implementation."""
import pathlib, struct, binascii, json
ROOT=pathlib.Path(__file__).resolve().parents[1]
def frame(op,seq,payload):
    raw=struct.pack('<BBHB',3,op,seq,len(payload))+payload
    raw+=struct.pack('<H',binascii.crc_hqx(raw,0xffff))
    wire=bytearray([0,0]);code_at=1;code=1
    for byte in raw:
        if byte:
            wire.append(byte);code+=1
        else:
            wire[code_at]=code;code_at=len(wire);wire.append(0);code=1
    wire[code_at]=code;wire.append(0)
    return raw,bytes(wire)
def rom(number):
    data=bytes([0x28,number,0,0,0,0,0]);crc=0
    for byte in data:
        for _ in range(8):
            mix=(crc^byte)&1;crc>>=1
            if mix:crc^=0x8c
            byte>>=1
    return data+bytes([crc])
def main():
    config=struct.pack('<8hHBBBH',176,8,168,8,400,16,560,16,200,3,2,0,600)+struct.pack("<4H",1000,100,30,60)
    bindings=rom(1)+rom(2)
    rows=[('hello_request',1,1,b''),('hello_locked_reply',0x81,1,bytes([0,3,64,5,15,5,2,4])),
      ('hello_enabled_reply',0x81,1,bytes([0,3,64,5,14,5,2,4])),('config_request',4,4,b''),
      ('set_config_request',5,5,config),('config_reply',0x84,4,bytes([0])+config+struct.pack('<4H',5,168,30,60)),
      ('get_bindings_request',14,14,b''),('set_bindings_request',15,15,bindings),
      ('get_bindings_reply',0x8e,14,bytes([0])+bindings),('version_rejected_reply',0x81,1,bytes([8])),
      ('maximum_payload',1,65535,bytes(range(64))),('wrap_sequence',2,0,b'')]
    data=[];cases=[]
    for index,(name,op,seq,payload) in enumerate(rows):
        raw,wire=frame(op,seq,payload)
        data.append(dict(name=name,version=3,opcode=op,sequence=seq,payload_hex=payload.hex().upper(),raw_hex=raw.hex().upper(),wire_hex=wire.hex().upper()))
        payload_c=','.join(str(x) for x in payload) or '0'
        wire_c=','.join(str(x) for x in wire)
        cases.append(f'  const uint8_t p{index}[]={{{payload_c}}}, w{index}[]={{{wire_c}}};\n'
          f'  n=phone_pack({op},{seq},p{index},{len(payload)},wire);\n'
          f'  if(n!=sizeof(w{index}) || memcmp(wire,w{index},n)) return {index+1};')
    (ROOT/'tests/phone_vectors.json').write_text(json.dumps(data,indent=2)+'\n')
    (ROOT/'tests/test_vectors.c').write_text('/* Generated by generate_vectors.py: independent expected bytes. */\n#include "phone_link.h"\n#include <string.h>\nuint32_t vectors_selftest(void)\n{\n  uint8_t wire[PHONE_WIRE_MAX];unsigned n;\n'+'\n'.join(cases)+'\n  return 0;\n}\n')
if __name__=='__main__':main()
